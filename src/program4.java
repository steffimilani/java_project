public class Main {
    public static void main(String[] args) {

        int a = 10;
        int b = 3;

        // Integer Division
        int intResult = a / b;
        System.out.println("Integer Division: " + intResult);

        // Floating-Point Division
        double floatResult = (double) a / b;
        System.out.println("Floating-Point Division: " + floatResult);
    }
}